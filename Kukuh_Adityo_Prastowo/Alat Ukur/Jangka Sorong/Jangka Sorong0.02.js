		          const unitStr = isMM ? "mm" : "cm";
		          const labelUnit = new createjs.Text(unitStr, fontStyle, "#000");
		          labelUnit.textAlign = "left";
		          labelUnit.textBaseline = "bottom";
		          
		          // Geser posisi satuan ke kanan dari tengah angka
